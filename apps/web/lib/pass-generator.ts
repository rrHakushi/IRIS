/**
 * Generates an unbiased cryptographically random integer in [0, max - 1].
 */
function getRandomInt(max: number): number {
  if (max <= 0) return 0
  const randomBuffer = new Uint32Array(1)
  const maxUint32 = 0xffffffff
  const limit = maxUint32 - (maxUint32 % max)

  let value: number
  do {
    crypto.getRandomValues(randomBuffer)
    value = randomBuffer[0] ?? 0
  } while (value >= limit)

  return value % max
}

/**
 * Generates a high-entropy random password.
 * NEVER retains or caches previous passwords.
 */
export function generatePassword(
  options: Partial<PasswordGeneratorOptions> = {}
): string {
  const opts: PasswordGeneratorOptions = {
    length: options.length ?? 16,
    uppercase: options.uppercase ?? true,
    lowercase: options.lowercase ?? true,
    numbers: options.numbers ?? true,
    symbols: options.symbols ?? true,
    minNumbers: options.minNumbers ?? 1,
    minSymbols: options.minSymbols ?? 1,
    avoidAmbiguous: options.avoidAmbiguous ?? true,
  }

  let upper = UPPERCASE_CHARS
  let lower = LOWERCASE_CHARS
  let nums = NUMBER_CHARS
  let syms = SYMBOL_CHARS

  if (opts.avoidAmbiguous) {
    const filterAmbiguous = (s: string) =>
      s
        .split("")
        .filter((c) => !AMBIGUOUS_CHARS.includes(c))
        .join("")
    upper = filterAmbiguous(upper)
    lower = filterAmbiguous(lower)
    nums = filterAmbiguous(nums)
    syms = filterAmbiguous(syms)
  }

  let pool = ""
  if (opts.uppercase) pool += upper
  if (opts.lowercase) pool += lower
  if (opts.numbers) pool += nums
  if (opts.symbols) pool += syms

  if (pool.length === 0) {
    pool = lower + nums
  }

  const resultChars: string[] = []

  // Ensure minimum numbers
  if (opts.numbers && nums.length > 0) {
    for (let i = 0; i < opts.minNumbers; i++) {
      const char = nums[getRandomInt(nums.length)]
      if (char) resultChars.push(char)
    }
  }

  // Ensure minimum symbols
  if (opts.symbols && syms.length > 0) {
    for (let i = 0; i < opts.minSymbols; i++) {
      const char = syms[getRandomInt(syms.length)]
      if (char) resultChars.push(char)
    }
  }

  // Fill remaining length
  while (resultChars.length < opts.length) {
    const char = pool[getRandomInt(pool.length)]
    if (char) resultChars.push(char)
  }

  // Fisher-Yates shuffle using cryptographically secure randomness
  for (let i = resultChars.length - 1; i > 0; i--) {
    const j = getRandomInt(i + 1)
    const charI = resultChars[i]
    const charJ = resultChars[j]
    if (charI !== undefined && charJ !== undefined) {
      resultChars[i] = charJ
      resultChars[j] = charI
    }
  }

  return resultChars.join("")
}

/**
 * Generates a Diceware passphrase using the curated wordlist.
 */
export function generatePassphrase(
  options: Partial<PassphraseGeneratorOptions> = {}
): string {
  const opts: PassphraseGeneratorOptions = {
    wordCount: options.wordCount ?? 4,
    separator: options.separator ?? "-",
    capitalize: options.capitalize ?? true,
    includeNumber: options.includeNumber ?? true,
  }

  const words: string[] = []
  for (let i = 0; i < opts.wordCount; i++) {
    let word = DICEWARE_WORDS[getRandomInt(DICEWARE_WORDS.length)] ?? "safe"
    if (opts.capitalize) {
      word = word.charAt(0).toUpperCase() + word.slice(1)
    }
    words.push(word)
  }

  let passphrase = words.join(opts.separator)
  if (opts.includeNumber) {
    const num = getRandomInt(100)
    passphrase += `${opts.separator}${num}`
  }

  return passphrase
}

/**
 * Generates a username or email alias.
 */
export function generateUsername(
  serviceName?: string,
  baseEmail?: string
): string {
  if (baseEmail && baseEmail.includes("@")) {
    const [local, domain] = baseEmail.split("@")
    const tag = serviceName
      ? serviceName.toLowerCase().replace(/[^a-z0-9]/g, "")
      : DICEWARE_WORDS[getRandomInt(DICEWARE_WORDS.length)]
    return `${local}+${tag}@${domain}`
  }

  const adj = DICEWARE_WORDS[getRandomInt(DICEWARE_WORDS.length)]
  const noun = DICEWARE_WORDS[getRandomInt(DICEWARE_WORDS.length)]
  const num = getRandomInt(900) + 100
  return `${adj}_${noun}${num}`
}

export interface PasswordEntropyScore {
  entropyBits: number
  score: 0 | 1 | 2 | 3 | 4 // 0: Very Weak, 1: Weak, 2: Fair, 3: Good, 4: Strong
  label: string
}

/**
 * Calculates Shannon entropy in bits for a given password string.
 */
export function calculatePasswordEntropy(
  password: string
): PasswordEntropyScore {
  if (!password || password.length === 0) {
    return { entropyBits: 0, score: 0, label: "Empty" }
  }

  let poolSize = 0
  if (/[a-z]/.test(password)) poolSize += 26
  if (/[A-Z]/.test(password)) poolSize += 26
  if (/[0-9]/.test(password)) poolSize += 10
  if (/[^a-zA-Z0-9]/.test(password)) poolSize += 32

  if (poolSize === 0) poolSize = 10

  const entropyBits = Math.round(
    password.length * (Math.log(poolSize) / Math.LN2)
  )

  if (entropyBits < 36) {
    return { entropyBits, score: 1, label: "Weak" }
  } else if (entropyBits < 56) {
    return { entropyBits, score: 2, label: "Fair" }
  } else if (entropyBits < 75) {
    return { entropyBits, score: 3, label: "Good" }
  } else {
    return { entropyBits, score: 4, label: "Very Strong" }
  }
}
